import { PlaceHolderImages } from './placeholder-images';

export interface Video {
  id: string;
  title: string;
  thumbnailUrl: string;
  videoUrl: string;
  thumbnailHint: string;
  videoHint: string;
}

export interface Character {
  id: string;
  name: string;
  iconUrl: string;
  iconHint: string;
  isLocked: boolean;
  videos: Video[];
}

const characterDetails: Omit<Character, 'iconUrl' | 'iconHint' | 'videos'>[] = [
    { id: 'fireplace', name: 'Cozy Fireplace', isLocked: false },
    { id: 'aquarium', name: 'Vibrant Aquarium', isLocked: false },
    { id: 'forest', name: 'Autumn Forest', isLocked: false },
    { id: 'rain', name: 'Rain on Window', isLocked: false },
    { id: 'beach', name: 'Sandy Beach', isLocked: false },
    { id: 'stream', name: 'Mountain Stream', isLocked: false },
    { id: 'zen', name: 'Zen Garden', isLocked: true },
    { id: 'snow', name: 'Snowy Cabin', isLocked: true },
    { id: 'city', name: 'City Rooftop', isLocked: true },
    { id: 'space', name: 'Space Nebula', isLocked: true },
    { id: 'waterfall', name: 'Tropical Waterfall', isLocked: true },
    { id: 'library', name: 'Library Ambiance', isLocked: true },
];

const findImage = (id: string) => {
    const img = PlaceHolderImages.find(p => p.id === id);
    if (!img) {
        const missingUrl = `https://picsum.photos/seed/${id}/400/400`;
        const hint = id.split('_')[1] || 'image';
        // To prevent crashes and keep the demo working, we generate a placeholder if one isn't found.
        // In a real app, you might throw an error or have a default image.
        // We also add it to the array to avoid repeated lookups for the same missing image.
        const newPlaceholder = { id, imageUrl: missingUrl, imageHint: hint, description: `Autogenerated for ${id}` };
        PlaceHolderImages.push(newPlaceholder);
        return { imageUrl: newPlaceholder.imageUrl, imageHint: newPlaceholder.imageHint };
    }
    return { imageUrl: img.imageUrl, imageHint: img.imageHint };
};

export const characters: Character[] = characterDetails.map(charDetail => {
    const { imageUrl: iconUrl, imageHint: iconHint } = findImage(`character_${charDetail.id}_icon`);
    
    const videos: Video[] = Array.from({ length: 6 }, (_, i) => {
        const videoNum = i + 1;
        const { imageUrl: thumbnailUrl, imageHint: thumbnailHint } = findImage(`character_${charDetail.id}_video_${videoNum}_thumb`);
        const { imageUrl: videoUrl, imageHint: videoHint } = findImage(`character_${charDetail.id}_video_${videoNum}_main`);
        
        return {
            id: `${charDetail.id}_video_${videoNum}`,
            title: `Scene ${videoNum}`,
            thumbnailUrl,
            thumbnailHint,
            videoUrl,
            videoHint,
        };
    });

    return {
        ...charDetail,
        iconUrl,
        iconHint,
        videos,
    };
});

export const getCharacterById = (id: string): Character | undefined => {
    return characters.find(c => c.id === id);
};
